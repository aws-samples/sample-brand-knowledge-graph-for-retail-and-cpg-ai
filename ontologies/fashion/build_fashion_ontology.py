"""Build ``fashion.ttl``, an OWL 2 ontology (Turtle) derived from the Fashionpedia vocabulary.

Fashionpedia (Jia et al., ECCV 2020) publishes an expert-built apparel ontology: 46 categories
(27 main apparel categories + 19 garment parts) and 294 fine-grained attributes in 11 attribute
families, licensed CC BY 4.0 (https://fashionpedia.github.io/home/data_license.html). This
script turns that flat catalog into a proper OWL ontology with rdflib:

* category groups (upper body, lower body, ...) become classes, categories become subclasses,
* attribute families become classes and each attribute value a named individual of its family,
* one ``has<Family>`` object property per family links garments to attribute values; the
  property domain (an ``owl:unionOf`` the applicable groups) encodes *applicability*, which
  Fashionpedia does not state formally,
* ``hasPart`` links garments to garment parts / closures / decorations,
* four jewelry categories that Fashionpedia does not have (earring, necklace, bracelet, ring)
  are added to the "others" group (``SAMPLE_CATEGORIES``), each marked as this sample's own,
* the brand knowledge-graph schema used by the rest of this sample (Look, Item, Statement,
  Article, Line, Brand and their relations) is added so the graph loader and the ontology
  explorer share one vocabulary,
* a closed vocabulary of occasions (``OCCASIONS``: the class Occasion, nine named individuals and
  the property ``for`` from Look to Occasion) is added, each term marked as this sample's own.

Only the *vocabulary* is used; no Fashionpedia image or annotation is included. The catalog has
names, supercategories and taxonomy ids but no description text: every definition in the output
(``rdfs:comment``, ``skos:definition``) is written here, for this sample.

``fashion.ttl`` is licensed under CC BY 4.0, not under the MIT-0 license of the rest of the
repository: the file starts with a comment that says so (``HEADER``), and the ontology carries
``dcterms:license`` and ``dcterms:rights``.

Usage:
    python3 ontologies/fashion/build_fashion_ontology.py            # downloads the catalog
    python3 ontologies/fashion/build_fashion_ontology.py catalog.json

Source catalog: data/demo/category_attributes_descriptions.json in
https://github.com/KMnP/fashionpedia-api (BSD-2-Clause).
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

from rdflib import DCTERMS, OWL, RDF, RDFS, SKOS, XSD, BNode, Graph, Literal, Namespace, URIRef
from rdflib.collection import Collection

HERE = Path(__file__).resolve().parent
OUT = HERE / "fashion.ttl"
CATALOG_URL = (
    "https://raw.githubusercontent.com/KMnP/fashionpedia-api/master/data/demo/"
    "category_attributes_descriptions.json"
)

FO = Namespace("http://example.org/multimodal-ai-knowledge-graph/fashion#")
# The first lines of fashion.ttl (Turtle comments, which rdflib's serializer cannot write).
HEADER = """\
# SPDX-License-Identifier: CC-BY-4.0
# ontologies/fashion/fashion.ttl is licensed under CC BY 4.0
# (https://creativecommons.org/licenses/by/4.0/), NOT under the MIT-0 license of the rest of this
# repository. It is derived from the Fashionpedia ontology by Menglin Jia, Mengyun Shi, Mikhail
# Sirotenko, Yin Cui, Claire Cardie, Bharath Hariharan, Hartwig Adam and Serge Belongie
# (ECCV 2020, https://fashionpedia.github.io/home/index.html). The changes made are listed in
# THIRD-PARTY-LICENSES and ontologies/fashion/README.md. The Fashionpedia authors do not endorse
# this sample. Generated by ontologies/fashion/build_fashion_ontology.py: do not edit by hand.

"""
RIGHTS = (
    "Licensed under CC BY 4.0, not under the MIT-0 license of the rest of the repository. Derived "
    "from the Fashionpedia ontology; the Fashionpedia authors do not endorse this sample. The "
    "definitions (rdfs:comment, skos:definition) are written for this sample."
)
ONTOLOGY_IRI = URIRef("http://example.org/multimodal-ai-knowledge-graph/fashion")
VERSION = "1.2.0"

# --- modelling choices layered on top of Fashionpedia -------------------------------------
# Which attribute families are meaningful for which category groups (Fashionpedia annotates
# attributes per mask without a formal applicability matrix).
APPLIES_TO: dict[str, list[str]] = {
    "silhouette": ["upperbody", "lowerbody", "wholebody"],
    "neckline type": ["upperbody", "wholebody"],
    "length": ["upperbody", "lowerbody", "wholebody"],
    "textile pattern": ["upperbody", "lowerbody", "wholebody", "neck", "head", "legs and feet"],
    "opening type": ["upperbody", "lowerbody", "wholebody", "legs and feet"],
    "waistline": ["lowerbody", "wholebody"],
    "textile finishing, manufacturing techniques": ["upperbody", "lowerbody", "wholebody"],
    "non-textile material type": ["legs and feet", "arms and hands", "head", "waist", "others"],
    "nickname": ["upperbody", "lowerbody", "wholebody", "legs and feet", "head"],
    "animal": ["legs and feet", "arms and hands", "others"],
    "leather": ["legs and feet", "arms and hands", "waist", "others"],
}

# supercategory -> (class local name, label, kind)
GROUPS: dict[str, tuple[str, str, str]] = {
    "upperbody": ("UpperBodyGarment", "Upper body", "item"),
    "lowerbody": ("LowerBodyGarment", "Lower body", "item"),
    "wholebody": ("WholeBodyGarment", "Whole body", "item"),
    "head": ("Headwear", "Head", "item"),
    "neck": ("Neckwear", "Neck", "item"),
    "arms and hands": ("ArmsAndHandsAccessory", "Arms and hands", "item"),
    "waist": ("WaistAccessory", "Waist", "item"),
    "legs and feet": ("LegsAndFeetwear", "Legs and feet", "item"),
    "others": ("OtherAccessory", "Other accessories", "item"),
    "garment parts": ("GarmentPart", "Garment parts", "part"),
    "closures": ("Closure", "Closures", "part"),
    "decorations": ("Decoration", "Decorations", "part"),
}

# Categories this sample adds; Fashionpedia has no jewelry. The lookbook data the sample is used
# with has earrings, necklaces, bracelets and rings, so they join "others" (other accessories,
# where the non-textile material, animal and leather families already apply). They take the
# shape of a Fashionpedia category, the name and its synonyms comma-separated, so the class,
# its skos:prefLabel and skos:altLabel come out the same way; they have no Fashionpedia
# taxonomy id, carry a definition (rdfs:comment) and say where they come from (SAMPLE_NOTE).
# A bare "cuff" or "chain" is left out on purpose: sleeves have cuffs, and belts and bag straps
# are chains too.
# (supercategory, name with synonyms, definition)
SAMPLE_CATEGORIES: list[tuple[str, str, str]] = [
    (
        "others",
        "earring, ear stud, hoop",
        "Jewelry worn on the ear, such as studs, hoops, drop and chandelier earrings.",
    ),
    (
        "others",
        "necklace, pendant, choker",
        "Jewelry worn around the neck, such as chains, pendants, chokers and strands of pearls "
        "or beads.",
    ),
    (
        "others",
        "bracelet, bangle, cuff bracelet",
        "Jewelry worn around the wrist, such as chain bracelets, bangles and cuffs.",
    ),
    ("others", "ring", "Jewelry worn on a finger, such as bands, cocktail and signet rings."),
]
SAMPLE_NOTE = "Added by this sample; not part of the Fashionpedia ontology."

# What a look is worn for: a closed list this sample adds (Fashionpedia has no occasion). A model
# answers with one of them for a photo as a whole (tab 2), and the deploy matches a data set's
# occasion text against their labels. The ids keep the underscores of the workshop's style DNA
# (occasion:business_casual), so they are written here and not made by slug(). Hidden labels
# (skos:hiddenLabel) are other words a data set may use; they are matched, never shown.
# (id, preferred label, hidden labels, definition)
OCCASIONS: list[tuple[str, str, list[str], str]] = [
    ("casual", "Casual", ["weekend", "everyday", "city", "relaxed"], "Relaxed everyday wear."),
    ("smart_casual", "Smart casual", [], "Casual pieces dressed up a step."),
    ("business_casual", "Business casual", [], "An office without a suit."),
    ("professional", "Professional", ["business", "office", "corporate"], "Tailored office wear."),
    ("evening", "Evening", ["dinner", "night out"], "An evening out: dinner, drinks, a show."),
    ("formal", "Formal", ["black tie", "gala"], "Black tie and formal events."),
    ("resort", "Resort", ["vacation", "holiday", "beach"], "Warm-weather travel and resort days."),
    ("outdoor", "Outdoor", ["outdoors", "hiking"], "Outdoor work and weather."),
    ("dress", "Dress", [], "A day look built around a dress."),
]

# attribute family (Fashionpedia supercategory) -> (class local name, property local name)
FAMILIES: dict[str, tuple[str, str]] = {
    "silhouette": ("Silhouette", "hasSilhouette"),
    "neckline type": ("NecklineType", "hasNecklineType"),
    "length": ("Length", "hasLength"),
    "textile pattern": ("TextilePattern", "hasTextilePattern"),
    "opening type": ("OpeningType", "hasOpeningType"),
    "waistline": ("Waistline", "hasWaistline"),
    "textile finishing, manufacturing techniques": ("TextileFinishing", "hasTextileFinishing"),
    "non-textile material type": ("NonTextileMaterial", "hasNonTextileMaterial"),
    "nickname": ("Nickname", "hasNickname"),
    "animal": ("AnimalMaterial", "hasAnimalMaterial"),
    "leather": ("LeatherType", "hasLeatherType"),
}


def slug(text: str, keep_qualifier: bool = False) -> str:
    """Stable id, identical to the ids the pipeline has always used.

    Qualifiers such as ``crew (neck)`` repeat the family name and are dropped, except for
    ``nickname`` values where the qualifier carries meaning (``polo (shirt)`` vs ``polo (collar)``).
    """
    if not keep_qualifier:
        text = re.sub(r"\(.*?\)", "", text)
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def pascal(text: str) -> str:
    return "".join(p.capitalize() for p in re.split(r"[^a-zA-Z0-9]+", text) if p)


def load_catalog(arg: str | None) -> dict:
    if arg:
        return json.loads(Path(arg).read_text())
    print(f"downloading {CATALOG_URL}")
    with urllib.request.urlopen(CATALOG_URL, timeout=30) as resp:  # nosec B310  # fixed https URL
        return json.loads(resp.read())


def add_class(
    g: Graph, iri: URIRef, label: str, parent: URIRef | None = None, comment: str | None = None
):
    g.add((iri, RDF.type, OWL.Class))
    g.add((iri, RDFS.label, Literal(label, lang="en")))
    if parent is not None:
        g.add((iri, RDFS.subClassOf, parent))
    if comment:
        g.add((iri, RDFS.comment, Literal(comment, lang="en")))


def add_object_property(
    g, iri, label, domain=None, range_=None, parent=None, comment=None, symmetric=False
):
    g.add((iri, RDF.type, OWL.ObjectProperty))
    if symmetric:
        g.add((iri, RDF.type, OWL.SymmetricProperty))
    g.add((iri, RDFS.label, Literal(label, lang="en")))
    if domain is not None:
        g.add((iri, RDFS.domain, domain))
    if range_ is not None:
        g.add((iri, RDFS.range, range_))
    if parent is not None:
        g.add((iri, RDFS.subPropertyOf, parent))
    if comment:
        g.add((iri, RDFS.comment, Literal(comment, lang="en")))


def union_of(g: Graph, members: list[URIRef]) -> URIRef | BNode:
    """``owl:unionOf`` class expression (a single member is returned as-is)."""
    if len(members) == 1:
        return members[0]
    node = BNode()
    g.add((node, RDF.type, OWL.Class))
    lst = BNode()
    Collection(g, lst, members)
    g.add((node, OWL.unionOf, lst))
    return node


def build(catalog: dict) -> Graph:
    g = Graph()
    g.bind("fo", FO)
    g.bind("owl", OWL)
    g.bind("rdfs", RDFS)
    g.bind("skos", SKOS)
    g.bind("dcterms", DCTERMS)
    g.bind("xsd", XSD)

    # ------------------------------------------------------------------ header / attribution
    g.add((ONTOLOGY_IRI, RDF.type, OWL.Ontology))
    g.add(
        (
            ONTOLOGY_IRI,
            RDFS.label,
            Literal("Fashion ontology for the multimodal AI knowledge graph sample", lang="en"),
        )
    )
    g.add((ONTOLOGY_IRI, OWL.versionInfo, Literal(VERSION)))
    g.add((ONTOLOGY_IRI, DCTERMS.license, URIRef("https://creativecommons.org/licenses/by/4.0/")))
    g.add((ONTOLOGY_IRI, DCTERMS.source, URIRef("https://fashionpedia.github.io/home/index.html")))
    g.add((ONTOLOGY_IRI, DCTERMS.creator, Literal("Amazon Web Services")))
    g.add((ONTOLOGY_IRI, DCTERMS.rights, Literal(RIGHTS, lang="en")))
    g.add(
        (
            ONTOLOGY_IRI,
            DCTERMS.bibliographicCitation,
            Literal(
                "Jia, M., Shi, M., Sirotenko, M., Cui, Y., Cardie, C., Hariharan, B., Adam, H., Belongie, S.: "
                "Fashionpedia: Ontology, Segmentation, and an Attribute Localization Dataset. ECCV 2020."
            ),
        )
    )
    g.add(
        (
            ONTOLOGY_IRI,
            RDFS.comment,
            Literal(
                "Category and attribute vocabulary reused from the Fashionpedia ontology (CC BY 4.0, "
                "https://fashionpedia.github.io/home/data_license.html). Changes made for this sample: "
                "the flat catalog is expressed in OWL 2 (groups and categories as classes, attribute "
                "families as classes with attribute values as named individuals, one has<Family> object "
                "property per family), an applicability matrix is added as property domains, hasPart "
                "links garments to parts/closures/decorations, four jewelry categories that "
                "Fashionpedia does not have (earring, necklace, bracelet, ring) are added to the "
                "group of other accessories, each marked with a skos:editorialNote, a brand "
                "knowledge-graph schema (Look, Item, Statement, Article, Line, Brand) is added, and "
                "a closed vocabulary of occasions (the class Occasion, nine named individuals and "
                "the property for from Look to Occasion) is added, each term marked with a "
                "skos:editorialNote. No Fashionpedia image or annotation is included.",
                lang="en",
            ),
        )
    )

    # ------------------------------------------------------------------ annotation properties
    for local, label, comment in [
        (
            "conceptId",
            "concept id",
            "Stable machine id used by the pipeline (e.g. 'coat', 'silhouette:a-line').",
        ),
        (
            "taxonomyId",
            "Fashionpedia taxonomy id",
            "Identifier of the concept in the Fashionpedia catalog.",
        ),
        (
            "visual",
            "visual concept",
            "false for schema concepts that cannot be observed in an image (used to exclude them from classification prompts).",
        ),
    ]:
        g.add((FO[local], RDF.type, OWL.AnnotationProperty))
        g.add((FO[local], RDFS.label, Literal(label, lang="en")))
        g.add((FO[local], RDFS.comment, Literal(comment, lang="en")))

    # ------------------------------------------------------------------ top-level classes
    add_class(
        g,
        FO.Apparel,
        "Apparel",
        comment="A wearable garment or accessory (the Fashionpedia main apparel categories and the "
        "jewelry this sample adds).",
    )
    add_class(
        g,
        FO.GarmentComponent,
        "Garment component",
        comment="A part, closure or decoration of a garment (Fashionpedia apparel parts).",
    )
    add_class(
        g,
        FO.Attribute,
        "Attribute value",
        comment="A fine-grained apparel attribute; each family is a subclass and each value a named individual.",
    )

    group_iri: dict[str, URIRef] = {}
    for supercat, (local, label, kind) in GROUPS.items():
        iri = FO[local]
        add_class(g, iri, label, FO.Apparel if kind == "item" else FO.GarmentComponent)
        g.add((iri, FO.conceptId, Literal(slug(supercat))))
        g.add((iri, SKOS.prefLabel, Literal(supercat, lang="en")))
        group_iri[supercat] = iri

    # ------------------------------------------------------------------ categories
    def add_category(name: str, supercat: str) -> tuple[URIRef, str]:
        parts = [p.strip() for p in name.split(",")]
        cid = slug(parts[0])
        iri = FO[pascal(parts[0])]
        add_class(g, iri, parts[0], group_iri[supercat])
        g.add((iri, SKOS.prefLabel, Literal(name, lang="en")))
        for alt in parts[1:]:
            g.add((iri, SKOS.altLabel, Literal(alt, lang="en")))
        g.add((iri, FO.conceptId, Literal(cid)))
        return iri, cid

    ids: list[str] = []
    for c in catalog["categories"]:
        iri, cid = add_category(c["name"], c["supercategory"])
        g.add((iri, FO.taxonomyId, Literal(c["taxonomy_id"])))
        ids.append(cid)
    for supercat, name, definition in SAMPLE_CATEGORIES:
        iri, cid = add_category(name, supercat)
        g.add((iri, RDFS.comment, Literal(definition, lang="en")))
        g.add((iri, SKOS.editorialNote, Literal(SAMPLE_NOTE, lang="en")))
        ids.append(cid)

    # ------------------------------------------------------------------ attribute families + values
    add_object_property(
        g,
        FO.hasAttribute,
        "has attribute",
        FO.Apparel,
        FO.Attribute,
        comment="Generic link from a garment to one of its attribute values; sub-properties are one per family.",
    )
    family_iri: dict[str, URIRef] = {}
    for fam, (cls_local, prop_local) in FAMILIES.items():
        cls = FO[cls_local]
        add_class(g, cls, fam, FO.Attribute)
        g.add((cls, FO.conceptId, Literal(slug(fam))))
        g.add((cls, SKOS.prefLabel, Literal(fam, lang="en")))
        family_iri[fam] = cls
        domain = union_of(g, [group_iri[s] for s in APPLIES_TO[fam]])
        add_object_property(g, FO[prop_local], prop_local, domain, cls, FO.hasAttribute)

    for a in catalog["attributes"]:
        fam = a["supercategory"]
        fam_id = slug(fam)
        aid = f"{fam_id}:{slug(a['name'], keep_qualifier=(fam == 'nickname'))}"
        iri = FO[f"{fam_id}_{aid.split(':', 1)[1]}"]
        g.add((iri, RDF.type, OWL.NamedIndividual))
        g.add((iri, RDF.type, family_iri[fam]))
        g.add((iri, RDFS.label, Literal(re.sub(r"\s*\(.*?\)", "", a["name"]).strip(), lang="en")))
        g.add((iri, SKOS.prefLabel, Literal(a["name"], lang="en")))
        g.add((iri, FO.conceptId, Literal(aid)))
        g.add((iri, FO.taxonomyId, Literal(a["taxonomy_id"])))
        ids.append(aid)

    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        sys.exit(f"duplicate concept ids: {dupes}")

    # ------------------------------------------------------------------ parts
    add_object_property(
        g,
        FO.hasPart,
        "has part",
        FO.Apparel,
        FO.GarmentComponent,
        comment="A garment part, closure or decoration visible on the garment.",
    )

    # ------------------------------------------------------------------ brand knowledge-graph schema
    schema = {
        "Look": "A styled outfit: an ordered set of items shown together (lookbook, campaign, editorial).",
        "Item": "A concrete catalog product; its category is one of the Apparel classes.",
        "Statement": "A single editorial claim extracted from an article (e.g. a styling rule or trend note).",
        "Article": "An editorial source document: magazine feature, brand blog post, lookbook text.",
        "Line": "A brand's product line or collection.",
        "Brand": "A brand (the fictional 'AnyCompany Apparel' in the sample data).",
    }
    for local, comment in schema.items():
        add_class(g, FO[local], local, comment=comment)
        g.add((FO[local], FO.visual, Literal(False)))
    add_object_property(
        g, FO.contains, "contains", FO.Look, FO.Item, comment="A look contains an item."
    )
    add_object_property(
        g,
        FO.layeredWith,
        "layered with",
        FO.Item,
        FO.Item,
        symmetric=True,
        comment="Two items worn layered in the same look.",
    )
    add_object_property(
        g,
        FO.isCategory,
        "is category",
        FO.Item,
        FO.Apparel,
        comment="The apparel category of an item.",
    )
    add_object_property(g, FO.fromLine, "from line", FO.Item, FO.Line)
    add_object_property(g, FO.ofBrand, "of brand", FO.Line, FO.Brand)
    add_object_property(g, FO.hasStatement, "has statement", FO.Article, FO.Statement)
    add_object_property(
        g,
        FO.illustrates,
        "illustrates",
        FO.Statement,
        union_of(g, [FO.Look, FO.Item, FO.Apparel]),
        comment="What an editorial statement is about.",
    )
    add_object_property(
        g,
        FO.pairsWith,
        "pairs with",
        FO.Apparel,
        FO.Apparel,
        symmetric=True,
        comment="Category-level styling rule: garments of these categories are recommended together.",
    )
    # Knowledge-graph relations are not observable in a photo: keep them out of vision prompts.
    for prop in (
        FO.contains,
        FO.layeredWith,
        FO.isCategory,
        FO.fromLine,
        FO.ofBrand,
        FO.hasStatement,
        FO.illustrates,
        FO.pairsWith,
    ):
        g.add((prop, FO.visual, Literal(False)))
    for local, label in [
        ("colorName", "color"),
        ("materialName", "material"),
        ("description", "description"),
    ]:
        g.add((FO[local], RDF.type, OWL.DatatypeProperty))
        g.add((FO[local], RDFS.label, Literal(label, lang="en")))
        g.add((FO[local], RDFS.domain, FO.Item))
        g.add((FO[local], RDFS.range, XSD.string))

    # ------------------------------------------------------------------ occasions (this sample's own)
    add_class(g, FO.Occasion, "Occasion", comment="What a look is worn for.")
    g.add((FO.Occasion, FO.conceptId, Literal("occasion")))
    g.add((FO.Occasion, SKOS.prefLabel, Literal("Occasion", lang="en")))
    add_object_property(
        g, FO["for"], "for", FO.Look, FO.Occasion, comment="The occasion a look is worn for."
    )
    for term in (FO.Occasion, FO["for"]):
        # Look is schema-only, but its occasion is judged from the photo as a whole
        g.add((term, FO.visual, Literal(True)))
        g.add((term, SKOS.editorialNote, Literal(SAMPLE_NOTE, lang="en")))
    for oid, label, hidden, definition in OCCASIONS:
        iri = FO[f"occasion_{oid}"]
        g.add((iri, RDF.type, OWL.NamedIndividual))
        g.add((iri, RDF.type, FO.Occasion))
        g.add((iri, RDFS.label, Literal(label, lang="en")))
        g.add((iri, SKOS.prefLabel, Literal(label, lang="en")))
        g.add((iri, SKOS.definition, Literal(definition, lang="en")))
        g.add((iri, FO.conceptId, Literal(f"occasion:{oid}")))
        for word in hidden:
            g.add((iri, SKOS.hiddenLabel, Literal(word, lang="en")))
        g.add((iri, SKOS.editorialNote, Literal(SAMPLE_NOTE, lang="en")))
    return g


def main(argv: list[str]) -> int:
    catalog = load_catalog(argv[1] if len(argv) > 1 else None)
    g = build(catalog)
    OUT.write_text(HEADER + g.serialize(format="turtle"), encoding="utf-8")
    n_classes = len(set(g.subjects(RDF.type, OWL.Class))) - len(set(g.subjects(OWL.unionOf, None)))
    n_ind = len(set(g.subjects(RDF.type, OWL.NamedIndividual)))
    n_obj = len(set(g.subjects(RDF.type, OWL.ObjectProperty)))
    print(
        f"wrote {OUT}: {n_classes} classes, {n_ind} individuals, {n_obj} object properties, {len(g)} triples"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
