import * as cdk from 'aws-cdk-lib';
import * as cognito from 'aws-cdk-lib/aws-cognito';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as lambda from 'aws-cdk-lib/aws-lambda';
import * as secretsmanager from 'aws-cdk-lib/aws-secretsmanager';
import { Construct } from 'constructs';
import { functionLogging } from './function-logging';

export interface AuthProps {
  /** The site managed login sends the browser back to (the CloudFront distribution): `https://<domain>`, no trailing slash. */
  readonly siteUrl: string;
  /** First block of the stack id: keeps the managed-login domain prefix and the secret name unique per stack. */
  readonly stackSuffix: string;
  /** Username and email of the one user (stack parameters). */
  readonly signInUser: string;
  readonly signInEmail: string;
  /** The stack's Lambda code and runtime: `ontology_rag.lambda_handler.auth_setup_handler` lives in the same zip. */
  readonly code: lambda.Code;
  readonly runtime: lambda.Runtime;
}

/**
 * Who may use the demo: one Amazon Cognito user pool with one user, managed login (authorization
 * code + PKCE, no client secret), and a Cognito identity pool that turns a signed-in user's ID
 * token into temporary AWS credentials of one IAM role (`signedInRole`). The browser signs its API
 * requests with those credentials, and IAM decides whether the API's function URL accepts them:
 * the sample's own code checks no token. Everything is plain CloudFormation resources plus one
 * custom resource backed by the stack's own code zip.
 *
 * The user's password is generated by Secrets Manager and set on the Cognito user by the
 * `Custom::AuthSetup` resource: it never appears in a template, an output or an email, and the
 * sample needs no email delivery to work. Deployers read it from Secrets Manager.
 */
export class Auth extends Construct {
  readonly userPool: cognito.UserPool;
  /** The browser's app client (web/src/auth.ts signs in with it). */
  readonly client: cognito.UserPoolClient;
  /** The managed-login host, `<prefix>.auth.<region>.amazoncognito.com`. */
  readonly domainHost: string;
  /** The identity pool that gives a signed-in user temporary credentials of `signedInRole`. */
  readonly identityPool: cognito.CfnIdentityPool;
  /** The role a signed-in user's credentials belong to; the stack lets it call the API's function URL and nothing else. */
  readonly signedInRole: iam.Role;

  constructor(scope: Construct, id: string, props: AuthProps) {
    super(scope, id);
    const stack = cdk.Stack.of(this);

    this.userPool = new cognito.UserPool(this, 'UserPool', {
      selfSignUpEnabled: false, // the stack creates the one user; nobody signs up
      signInAliases: { username: true, email: true },
      autoVerify: { email: true },
      passwordPolicy: {
        minLength: 12,
        requireLowercase: true,
        requireUppercase: true,
        requireDigits: true,
        requireSymbols: true,
        tempPasswordValidity: cdk.Duration.days(3),
      },
      // Optional TOTP: SMS would need an SNS sending role and spend. Essentials (no charge at the
      // demo's size) has everything the demo uses; threat protection needs Plus (see COG8 below).
      mfa: cognito.Mfa.OPTIONAL,
      mfaSecondFactor: { otp: true, sms: false },
      accountRecovery: cognito.AccountRecovery.EMAIL_ONLY,
      featurePlan: cognito.FeaturePlan.ESSENTIALS,
      deletionProtection: false,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });
    cdk.Validations.of(this.userPool).acknowledge(
      { id: 'AwsSolutions-COG2', reason: 'MFA is optional by design: one demo user, who may enrol a TOTP authenticator' },
      {
        id: 'AwsSolutions-COG8',
        reason:
          'threat protection (compromised-credential checks and adaptive authentication) needs the Plus plan, about $0.02 per active ' +
          'user per month; the demo stays on Essentials because its one password is a generated 24-character secret that ' +
          'compromised-credential checks would not find, and adaptive authentication could challenge workshop sign-ins that ' +
          'all come from one shared venue network',
      },
    );

    // Managed login (the newer, branded sign-in pages) on a Cognito prefix domain.
    const domain = this.userPool.addDomain('Domain', {
      cognitoDomain: { domainPrefix: cdk.Fn.join('-', ['multimodal-ai-knowledge-graph', props.stackSuffix]) },
      managedLoginVersion: cognito.ManagedLoginVersion.NEWER_MANAGED_LOGIN,
    });
    this.domainHost = `${domain.domainName}.auth.${stack.region}.amazoncognito.com`;

    // A public client for the browser: authorization code grant with PKCE (oidc-client-ts). The
    // explicit auth flows are SRP and refresh token only: no USER_PASSWORD_AUTH (the password would
    // travel in a request), no custom auth, no implicit grant, no client credentials.
    const client = (this.client = this.userPool.addClient('WebClient', {
      generateSecret: false,
      authFlows: { userSrp: true },
      oAuth: {
        flows: { authorizationCodeGrant: true },
        scopes: [cognito.OAuthScope.OPENID, cognito.OAuthScope.EMAIL, cognito.OAuthScope.PROFILE],
        callbackUrls: [`${props.siteUrl}/`],
        logoutUrls: [`${props.siteUrl}/`],
      },
      preventUserExistenceErrors: true,
      enableTokenRevocation: true,
      accessTokenValidity: cdk.Duration.hours(1),
      idTokenValidity: cdk.Duration.hours(1),
      refreshTokenValidity: cdk.Duration.hours(8),
    }));
    // Managed login needs a branding (the Cognito defaults) per client, on a managed-login domain.
    const branding = new cognito.CfnManagedLoginBranding(this, 'Branding', {
      userPoolId: this.userPool.userPoolId,
      clientId: client.userPoolClientId,
      useCognitoProvidedValues: true,
    });
    branding.node.addDependency(domain);

    // The identity pool: a signed-in user's ID token from this client buys temporary credentials of
    // signedInRole (the enhanced flow, GetId + GetCredentialsForIdentity). No guest identities, no
    // classic flow; serverSideTokenCheck makes Cognito refuse a token that was revoked or signed out.
    this.identityPool = new cognito.CfnIdentityPool(this, 'IdentityPool', {
      allowUnauthenticatedIdentities: false,
      allowClassicFlow: false,
      cognitoIdentityProviders: [
        { clientId: client.userPoolClientId, providerName: this.userPool.userPoolProviderName, serverSideTokenCheck: true },
      ],
    });
    // Only Cognito, only for this identity pool, only for signed-in identities may assume the role.
    // Its permissions are added by the stack: invoke the API's function URL, nothing else.
    this.signedInRole = new iam.Role(this, 'SignedInRole', {
      description: 'multimodal-ai-knowledge-graph: credentials of a signed-in user (Cognito identity pool); may call the API function URL only',
      assumedBy: new iam.FederatedPrincipal(
        'cognito-identity.amazonaws.com',
        {
          StringEquals: { 'cognito-identity.amazonaws.com:aud': this.identityPool.ref },
          'ForAnyValue:StringLike': { 'cognito-identity.amazonaws.com:amr': 'authenticated' },
        },
        'sts:AssumeRoleWithWebIdentity',
      ),
      maxSessionDuration: cdk.Duration.hours(1),
    });
    new cognito.CfnIdentityPoolRoleAttachment(this, 'IdentityPoolRoles', {
      identityPoolId: this.identityPool.ref,
      roles: { authenticated: this.signedInRole.roleArn },
    });

    // The one user. SUPPRESS: no invitation email with a temporary password; the password comes
    // from Secrets Manager (below), so the sample works without any email delivery.
    const user = new cognito.CfnUserPoolUser(this, 'SignInUser', {
      userPoolId: this.userPool.userPoolId,
      username: props.signInUser,
      userAttributes: [
        { name: 'email', value: props.signInEmail },
        { name: 'email_verified', value: 'true' },
      ],
      messageAction: 'SUPPRESS',
    });
    const secret = new secretsmanager.Secret(this, 'SignInPassword', {
      secretName: cdk.Fn.join('/', ['multimodal-ai-knowledge-graph', props.stackSuffix, 'sign-in']),
      description: 'multimodal-ai-knowledge-graph: password of the sign-in user (set on the Cognito user at deploy time)',
      generateSecretString: {
        passwordLength: 24,
        requireEachIncludedType: true,
        // Only symbols that survive a copy from the console or a shell without escaping.
        excludeCharacters: '"\'`,./:;<>?[\\]{|}~',
      },
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });
    cdk.Validations.of(secret).acknowledge({
      id: 'AwsSolutions-SMG4',
      reason: 'rotating the password would have to re-run Custom::AuthSetup on the Cognito user; the stack is short-lived and the secret dies with it',
    });

    // Sets the generated password on the user (permanent, so the first sign-in is not a forced
    // password change). Same no-framework custom-resource pattern as GraphLoader: the handler is
    // in the stack's code zip, the one the API runs.
    const setupFn = new lambda.Function(this, 'SetupFunction', {
      ...functionLogging(this, 'Setup'),
      runtime: props.runtime,
      code: props.code,
      handler: 'ontology_rag.lambda_handler.auth_setup_handler',
      memorySize: 512,
      timeout: cdk.Duration.minutes(2),
      description: 'multimodal-ai-knowledge-graph: sets the sign-in user password from Secrets Manager (CFN custom resource)',
    });
    setupFn.addToRolePolicy(
      new iam.PolicyStatement({ actions: ['cognito-idp:AdminSetUserPassword'], resources: [this.userPool.userPoolArn] }),
    );
    setupFn.addToRolePolicy(new iam.PolicyStatement({ actions: ['secretsmanager:GetSecretValue'], resources: [secret.secretArn] }));
    const setup = new cdk.CfnResource(this, 'Setup', {
      type: 'Custom::AuthSetup',
      properties: {
        ServiceToken: setupFn.functionArn,
        UserPoolId: this.userPool.userPoolId,
        Username: props.signInUser,
        SecretArn: secret.secretArn,
        // A changed user (CloudFormation replaces it, and the new one has no password) or a
        // replaced secret re-runs the handler on the next deploy.
        Version: cdk.Fn.join('|', [props.signInUser, props.signInEmail, secret.secretArn]),
      },
    });
    setup.node.addDependency(user, secret);

    // Stack-level names (`SignInUrl`, not a construct path with a hash); the password stays in
    // Secrets Manager because outputs are not confidential.
    const output = (name: string, value: string, description: string) => {
      new cdk.CfnOutput(this, `${name}Output`, { value, description }).overrideLogicalId(name);
    };
    output('UserPoolId', this.userPool.userPoolId, 'The Cognito user pool of the demo');
    output('IdentityPoolId', this.identityPool.ref, 'The Cognito identity pool that gives the signed-in user credentials for the API');
    output('SignInUser', props.signInUser, 'Username to sign in with');
    output('SignInPasswordSecret', secret.secretName, 'Secrets Manager secret holding the password of the sign-in user');
    output('SignInUrl', props.siteUrl, 'Open this to sign in (the site)');
  }
}
